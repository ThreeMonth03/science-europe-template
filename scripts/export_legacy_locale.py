"""Build a generated zh-Hant DT for stock DSW 4.34 from an English ZIP and PO.

No Jinja translation rewriting, document generation, upload, or source mutation.
The input ZIP must already contain the prepared fonts and Word reference.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import uuid
import zipfile
from collections import Counter
from pathlib import Path, PurePosixPath

import polib
from jinja2 import Environment

LANGUAGE_FILE = "src/locales/language.j2"
MO_FILE = "src/i18n/zh-Hant/LC_MESSAGES/dsw.mo"
I18N_OPTIONS = {
    "i18n-dir": "src/i18n",
    "i18n-domain": "dsw",
    "i18n-lang": "zh-Hant",
    "policy.ext.i18n.trimmed": "true",
}
FORMAT_NAMES = {
    "a9293d08-59a4-4e6b-ae62-7a6a570b031c": "HTML — 內部檢核版",
    "68c26e34-5e77-4e15-9bf7-06ff92582257": "PDF — 內部檢核版",
    "f4bd941a-dfbe-4226-a1fc-200fb5269311": "Word — 內部檢核版",
    "499d9300-0183-5157-b6f4-38e6c2b91600": "HTML — 提交版",
    "9fd0a115-4b8b-5013-a084-eaf2890ec940": "PDF — 提交版",
    "98081811-41ff-5438-b98a-0472607527c6": "Word — 提交版",
}
PARAMETER = r"%\(([^)]+)\)([-+#0 ]*\d*(?:\.\d+)?[diouxXeEfFgGcrsa])"


class ExportError(ValueError):
    """Input cannot be exported without an ambiguous or incomplete translation."""


def digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def require(ok: bool, message: str) -> None:
    if not ok:
        raise ExportError(message)


def catalog(files: list[dict], po_path: Path) -> tuple[bytes, int]:
    """Validate exact marked keys and named substitutions before compiling MO."""
    environment = Environment(
        extensions=["jinja2.ext.i18n", "jinja2.ext.do", "jinja2.ext.loopcontrols"]
    )
    environment.policies["ext.i18n.trimmed"] = True
    marked = set()
    for file in files:
        if not file["fileName"].endswith((".j2", ".jinja", ".jinja2", ".jnj")):
            continue
        for _, function, message in environment.extract_translations(file["content"]):
            require(
                function not in {"ngettext", "npgettext"},
                "Plural messages need a reviewed export rule",
            )
            args = message if isinstance(message, tuple) else (message,)
            context, text = (args[0], args[1]) if function == "pgettext" else (None, args[0])
            require(
                isinstance(text, str) and (context is None or isinstance(context, str)),
                "Translation keys must be static strings",
            )
            marked.add((context, text))
    po = polib.pofile(str(po_path))
    require(po.metadata.get("Language") == "zh-Hant", "PO Language must be zh-Hant")
    entries = [entry for entry in po if not entry.obsolete]
    keys = [(entry.msgctxt, entry.msgid) for entry in entries]
    require(len(keys) == len(set(keys)), "Duplicate PO translation keys")
    require(
        set(keys) == marked,
        "PO keys do not exactly match the English template (missing or extra keys)",
    )
    for entry in entries:
        require(
            bool(entry.msgstr.strip()) and "fuzzy" not in entry.flags and not entry.msgid_plural,
            "PO has an untranslated, fuzzy or plural message: " + entry.msgid,
        )

        def parameters(value: str) -> Counter:
            return Counter(
                (m.group(1), m.group(2))
                for m in re.finditer(r"%%|" + PARAMETER, value)
                if m.group(1)
            )

        require(
            parameters(entry.msgid) == parameters(entry.msgstr),
            "PO placeholder mismatch: " + entry.msgid,
        )
        for value in (entry.msgid, entry.msgstr):
            require(
                "%" not in re.sub(r"%%|" + PARAMETER, "", value),
                "PO has an unescaped percent: " + entry.msgid,
            )
    return po.to_binary(), len(entries)


def export_bundle(
    source_zip: Path, po_path: Path, output: Path, version: str, source_commit: str | None = None
) -> dict:
    """Export immutable generated bytes; a new PO publication needs a new version."""
    require(bool(re.fullmatch(r"\d+\.\d+\.\d+", version)), "Use an explicit x.y.z release version")
    require(
        source_commit is None or bool(re.fullmatch(r"[0-9a-f]{40}", source_commit)),
        "source_commit must be a full commit hash",
    )
    source_zip, po_path, output = [path.resolve() for path in (source_zip, po_path, output)]
    sidecar = output.with_suffix(output.suffix + ".json")
    require(
        output not in {source_zip, po_path} and not output.exists() and not sidecar.exists(),
        "Refuse to overwrite an input or existing output",
    )
    with zipfile.ZipFile(source_zip) as archive:
        infos = archive.infolist()
        names = [item.filename for item in infos]
        require(len(names) == len(set(names)), "Duplicate ZIP members")
        require(
            sum(item.file_size for item in infos) <= 512 * 1024 * 1024, "ZIP expands beyond 512 MiB"
        )
        require(
            all(
                not PurePosixPath(name).is_absolute()
                and ".." not in PurePosixPath(name).parts
                and "\\" not in name
                for name in names
            ),
            "Unsafe ZIP member path",
        )
        require("template/template.json" in names, "Expected an official TDK template bundle")
        members = {name: archive.read(name) for name in names if not name.endswith("/")}
    payload = json.loads(members["template/template.json"])
    require(
        payload.get("language") == "en",
        "Export only the canonical English package, not a translated export",
    )
    require(
        payload.get("metamodelVersion") in {"18.0", "18.1", "18.2"},
        "Unsupported 4.34 template metamodel",
    )
    files, assets = payload["files"], payload["assets"]
    paths = [item["fileName"] for item in files + assets]
    require(
        len(paths) == len(set(paths)) and LANGUAGE_FILE in paths and MO_FILE not in paths,
        "Duplicate files, missing language helper, or already-exported MO",
    )
    require(
        all(
            not PurePosixPath(name).is_absolute()
            and ".." not in PurePosixPath(name).parts
            and "\\" not in name
            for name in paths
        ),
        "Unsafe template file path",
    )
    require(
        all("template/assets/" + item["fileName"] in members for item in assets),
        "Missing binary asset",
    )
    require(
        not any(
            key in step.get("options", {})
            for fmt in payload["formats"]
            for step in fmt["steps"]
            for key in ("i18n-dir", "i18n-domain", "i18n-lang")
        ),
        "Input is already a legacy translation profile",
    )
    mo, count = catalog(files, po_path)
    source_hash, po_hash = digest(source_zip.read_bytes()), digest(po_path.read_bytes())
    coordinate = f"{payload['organizationId']}:{payload['templateId']}-zhtw-compat434:{version}"
    namespace = f"dsw-legacy434-v1:{coordinate}:{source_hash}:{po_hash}"
    for file in files:
        if file["fileName"] == LANGUAGE_FILE:
            file["content"] = "zh-Hant"  # old contexts have no selected document locale
    payload["templateId"] += "-zhtw-compat434"
    payload.update(
        id=coordinate,
        version=version,
        language="zh-Hant",
        name="Science Europe 資料管理方案（DSW 4.34 中文相容版）",
        description="由英文模板與中文 PO 自動產生。適用 DSW 4.34；4.35 請使用正式 PO 版本。",
    )
    supported = [fmt for fmt in payload["formats"] if fmt["uuid"] in FORMAT_NAMES]
    require(
        {fmt["uuid"] for fmt in supported} == set(FORMAT_NAMES),
        "Expected all six HTML/PDF/Word profiles",
    )
    payload["formats"] = supported
    for fmt in supported:
        fmt["name"] = FORMAT_NAMES[fmt["uuid"]]
        for step in fmt["steps"]:
            if step["name"] in {"jinja", "enrich-docx"}:
                options = step.setdefault("options", {})
                extensions = set(
                    filter(None, (v.strip() for v in options.get("jinja-ext", "").split(",")))
                )
                options.update(I18N_OPTIONS)
                options["jinja-ext"] = ",".join(sorted(extensions | {"i18n"}))
    assets.append({"fileName": MO_FILE, "contentType": "application/octet-stream"})
    for kind, items in (("files", files), ("assets", assets)):
        for item in items:
            item["uuid"] = str(
                uuid.uuid5(uuid.NAMESPACE_URL, f"{namespace}:{kind}:{item['fileName']}")
            )
    members["template/template.json"] = (
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    ).encode()
    members["template/assets/" + MO_FILE] = mo
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "x", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, value in sorted(members.items()):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, value, compresslevel=9)
    manifest = {
        "profile": "legacy434-zh-Hant-v1",
        "target_worker": "4.34",
        "template_id": coordinate,
        "source_commit": source_commit,
        "source_zip_sha256": source_hash,
        "po_sha256": po_hash,
        "mo_sha256": digest(mo),
        "output_zip_sha256": digest(output.read_bytes()),
        "approved_messages": count,
        "formats": list(FORMAT_NAMES),
        "changed_render_source_files": [LANGUAGE_FILE],
        "original_assets_preserved": True,
        "generated_do_not_edit": True,
        "publication_rule": (
            "New source/PO publication requires a new DT version; "
            "never overwrite an installed coordinate."
        ),
    }
    with sidecar.open("x", encoding="utf-8") as stream:
        json.dump(manifest, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-zip", type=Path, required=True)
    parser.add_argument("--po", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--version", required=True)
    parser.add_argument("--source-commit")
    args = parser.parse_args()
    print(
        json.dumps(
            export_bundle(args.source_zip, args.po, args.output, args.version, args.source_commit),
            ensure_ascii=False,
            indent=2,
        )
    )
